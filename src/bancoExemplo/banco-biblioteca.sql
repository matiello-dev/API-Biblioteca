DROP TABLE IF EXISTS emprestimos CASCADE;
DROP TABLE IF EXISTS leitores CASCADE;
DROP TABLE IF EXISTS exemplares CASCADE;
DROP TABLE IF EXISTS livro_autor CASCADE;
DROP TABLE IF EXISTS livros CASCADE;
DROP TABLE IF EXISTS autores CASCADE;
DROP TABLE IF EXISTS editoras CASCADE;

CREATE TABLE editoras (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(80) NOT NULL UNIQUE,
  cidade VARCHAR(60) NOT NULL
);

CREATE TABLE autores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  nacionalidade VARCHAR(40)
);

CREATE TABLE livros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(150) NOT NULL,
  isbn CHAR(13) NOT NULL UNIQUE,
  ano INTEGER NOT NULL CHECK (ano BETWEEN 1450 AND 2100),
  editora_id INTEGER NOT NULL REFERENCES editoras(id)
);

-- N:N entre livros e autores
CREATE TABLE livro_autor (
  livro_id INTEGER NOT NULL REFERENCES livros(id),
  autor_id INTEGER NOT NULL REFERENCES autores(id),
  PRIMARY KEY (livro_id, autor_id)
);

CREATE TABLE exemplares (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  livro_id INTEGER NOT NULL REFERENCES livros(id),
  codigo VARCHAR(12) NOT NULL UNIQUE,
  estado VARCHAR(12) NOT NULL DEFAULT 'disponivel'
    CHECK (estado IN ('disponivel', 'emprestado', 'manutencao', 'perdido'))
);

CREATE TABLE leitores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  cpf CHAR(11) NOT NULL UNIQUE,
  email VARCHAR(120) NOT NULL UNIQUE,
  telefone VARCHAR(20),
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE emprestimos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exemplar_id INTEGER NOT NULL REFERENCES exemplares(id),
  leitor_id INTEGER NOT NULL REFERENCES leitores(id),
  emprestado_em DATE NOT NULL DEFAULT CURRENT_DATE,
  devolver_ate DATE NOT NULL,
  devolvido_em DATE,
  multa NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (multa >= 0),
  CHECK (devolver_ate > emprestado_em),
  CHECK (devolvido_em IS NULL OR devolvido_em >= emprestado_em),
  -- restrição própria 1: prazo máximo de 30 dias
  CONSTRAINT emprestimos_prazo_maximo CHECK (devolver_ate <= emprestado_em + 30)
);

-- restrição própria 2: um exemplar só pode ter um empréstimo em aberto
CREATE UNIQUE INDEX emprestimos_um_aberto_por_exemplar
  ON emprestimos (exemplar_id) WHERE devolvido_em IS NULL;

